#!/usr/bin/env node
/**
 * Contracts generator.
 *
 * Reads the backend's published contract files and writes TypeScript into
 * lib/contracts/generated/**:
 *   - openapi.ts : `paths` / `components` types from docs/api/openapi.json (openapi-typescript)
 *   - states.ts  : the 12-state taxonomy and the reasonCode -> state map from docs/api/STATES.md
 *   - sse.ts     : the SSE event catalogue from docs/api/SSE.md
 *
 * Usage: node scripts/gen-contracts.mjs            (uses ../../nearesis-app/docs/api)
 *        NEARESIS_API_DOCS=/path/to/docs/api node scripts/gen-contracts.mjs
 * The generated files are committed so a standalone clone builds without the backend repo.
 * Never edit them by hand; re-run this script when the backend contract changes.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const docs = process.env.NEARESIS_API_DOCS ?? path.resolve(root, '../../nearesis-app/docs/api');
const out = path.join(root, 'lib/contracts/generated');
mkdirSync(out, { recursive: true });

for (const f of ['openapi.json', 'STATES.md', 'SSE.md']) {
  if (!existsSync(path.join(docs, f))) {
    console.error(`missing ${path.join(docs, f)} (set NEARESIS_API_DOCS)`);
    process.exit(1);
  }
}

const HEADER = '/* eslint-disable */\n// GENERATED by scripts/gen-contracts.mjs from the backend contract files. Do not edit by hand.\n\n';

// ---- openapi types -------------------------------------------------------
const spec = JSON.parse(readFileSync(path.join(docs, 'openapi.json'), 'utf8'));
const ast = await openapiTS(pathToFileURL(path.join(docs, 'openapi.json')));
writeFileSync(path.join(out, 'openapi.ts'), HEADER + `// contracts ${spec.info.version}\n` + astToString(ast));

// ---- states --------------------------------------------------------------
const states = readFileSync(path.join(docs, 'STATES.md'), 'utf8');
const stateRows = [];
const reasonRows = [];
for (const line of states.split('\n')) {
  const cells = line.split('|').map((c) => c.trim());
  if (cells.length < 4) continue;
  const m = /^`([a-z_]+)`$/.exec(cells[1] ?? '');
  if (m && cells.length >= 7) {
    stateRows.push({ state: m[1], kind: cells[2], retryable: cells[3] === 'yes', meaning: cells[4], frontend: cells[5] });
    continue;
  }
  const r = /^`([A-Z_]+)`$/.exec(cells[1] ?? '');
  const s = /^`([a-z_]+)`$/.exec(cells[2] ?? '');
  if (r && s) reasonRows.push([r[1], s[1]]);
}
if (stateRows.length !== 12) throw new Error(`expected 12 states in STATES.md, parsed ${stateRows.length}`);
const q = (s) => JSON.stringify(s);
let st = HEADER;
st += `export const API_STATES = [${stateRows.map((r) => q(r.state)).join(', ')}] as const;\nexport type ApiState = (typeof API_STATES)[number];\n\n`;
st += `export const STATE_INFO: Record<ApiState, { kind: 'data' | 'refusal'; retryable: boolean; meaning: string; frontend: string }> = {\n`;
for (const r of stateRows) st += `  ${r.state}: { kind: ${q(r.kind)}, retryable: ${r.retryable}, meaning: ${q(r.meaning)}, frontend: ${q(r.frontend)} },\n`;
st += `};\n\nexport const REASON_STATE: Record<string, ApiState> = {\n`;
for (const [r, s] of reasonRows) st += `  ${r}: ${q(s)},\n`;
st += `};\n`;
writeFileSync(path.join(out, 'states.ts'), st);

// ---- sse -----------------------------------------------------------------
const sse = readFileSync(path.join(docs, 'SSE.md'), 'utf8');
const events = [];
for (const line of sse.split('\n')) {
  const c = line.split('|').map((x) => x.trim());
  const e = /^`([a-z_.]+)`$/.exec(c[1] ?? '');
  const sch = /^`(Sse[A-Za-z]+)`$/.exec(c[2] ?? '');
  if (e && sch) events.push({ name: e[1], schema: sch[1], id: c[3], ends: c[4] === 'yes', meaning: c[5] });
}
if (events.length < 30) throw new Error(`SSE catalogue parse looks wrong: ${events.length} events`);
let se = HEADER;
se += `import type { components } from './openapi';\n\n`;
se += `export const SSE_EVENTS = {\n`;
for (const e of events) se += `  ${q(e.name)}: { schema: ${q(e.schema)}, endsStream: ${e.ends}, hasId: ${e.id === 'seq'} },\n`;
se += `} as const;\n\nexport type SseEventName = keyof typeof SSE_EVENTS;\n`;
se += `export const SSE_EVENT_NAMES = Object.keys(SSE_EVENTS) as SseEventName[];\n\n`;
se += `type Schemas = components['schemas'];\nexport type SseDataByEvent = {\n`;
for (const e of events) se += `  ${q(e.name)}: ${e.schema in (spec.components?.schemas ?? {}) ? `Schemas[${q(e.schema)}]` : 'unknown'};\n`;
se += `};\n\nexport type SseFrame<N extends SseEventName = SseEventName> = {\n  [K in N]: { event: K; seq: number | null; data: SseDataByEvent[K] };\n}[N];\n`;
writeFileSync(path.join(out, 'sse.ts'), se);

writeFileSync(
  path.join(out, 'index.ts'),
  HEADER + `export type { paths, components, operations } from './openapi';\nexport * from './states';\nexport * from './sse';\n`,
);
console.log(`generated contracts ${spec.info.version}: ${stateRows.length} states, ${reasonRows.length} reason codes, ${events.length} events`);
