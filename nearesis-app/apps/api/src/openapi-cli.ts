import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import * as contracts from "@nearesis/contracts";
import type { NamedSchema } from "@nearesis/contracts";
import {
  API_STATES,
  API_STATE_INFO,
  REASON_CODE_STATE,
  SSE_EVENTS,
  SSE_SEMANTICS,
  buildOpenApi,
} from "@nearesis/contracts";
import { EXTRA_SCHEMAS, ROUTES } from "./openapi-routes.ts";

/**
 * `pnpm api:openapi` writes docs/api/openapi.json, docs/api/SSE.md and docs/api/STATES.md from the zod contracts and the
 * route table. `pnpm api:openapi --check` writes nothing and exits 1 when a committed file differs (CI drift check).
 */
export const DOCS_API_DIR = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..", "docs", "api");

/** Every zod schema exported by the contracts package, by export name. */
export const KNOWN_SCHEMAS: NamedSchema[] = (Object.entries(contracts) as Array<[string, unknown]>)
  .filter(([, v]) => v instanceof z.ZodType)
  .map(([name, schema]) => ({ name, schema: schema as z.ZodType }));

export function buildSpec() {
  return buildOpenApi({ routes: ROUTES, schemas: EXTRA_SCHEMAS, known: KNOWN_SCHEMAS });
}

export function sseMarkdown(): string {
  const l: string[] = [];
  l.push(
    "# SSE event catalogue",
    "",
    "Generated by `pnpm api:openapi` from `packages/contracts/src/openapi-sse.ts`. Do not edit by hand.",
    "",
  );
  l.push(
    `Endpoint: \`${SSE_SEMANTICS.endpoint}\` (\`${SSE_SEMANTICS.contentType}\`).`,
    "",
    "## Framing",
    "",
    SSE_SEMANTICS.framing,
    "",
  );
  l.push("## Ordering", "", ...SSE_SEMANTICS.ordering.map((x) => `- ${x}`), "");
  l.push("## Resume", "", ...SSE_SEMANTICS.resume.map((x) => `- ${x}`), "");
  l.push("## Limits", "", ...SSE_SEMANTICS.limits.map((x) => `- ${x}`), "");
  l.push("## Authorization", "", SSE_SEMANTICS.authorization, "");
  l.push("## Events", "", "| Event | Schema | `id:` | Ends stream | Meaning |", "|---|---|---|---|---|");
  for (const e of SSE_EVENTS)
    l.push(
      `| \`${e.event}\` | \`${e.schema}\` | ${e.hasId ? "seq" : "none"} | ${e.terminal ? "yes" : "no"} | ${e.description.replace(/\|/g, "/")} |`,
    );
  l.push("", "Sample transcript: `docs/api/examples/sse-session.txt`.", "");
  return l.join("\n");
}

export function statesMarkdown(): string {
  const l: string[] = [];
  l.push(
    "# State and error taxonomy",
    "",
    "Generated by `pnpm api:openapi` from `packages/contracts/src/openapi-states.ts`. Do not edit by hand.",
    "",
  );
  l.push(
    `Exactly ${API_STATES.length} states. \`ErrorResponse.state\` (v1.7.0, additive and optional) carries one for refusals; data envelopes carry \`DataStateEnvelope.state\`. \`errorCode\`, \`reasonCode\` and the HTTP status are unchanged.`,
    "",
  );
  l.push("| State | Kind | Retryable | Meaning | Frontend |", "|---|---|---|---|---|");
  for (const s of API_STATES) {
    const i = API_STATE_INFO[s];
    l.push(`| \`${s}\` | ${i.kind} | ${i.retryable ? "yes" : "no"} | ${i.summary} | ${i.frontend} |`);
  }
  l.push("", "## Reason code mapping", "", "| reasonCode | state |", "|---|---|");
  for (const [k, v] of Object.entries(REASON_CODE_STATE).sort(([a], [b]) => (a < b ? -1 : 1)))
    l.push(`| \`${k}\` | \`${v}\` |`);
  l.push(
    "",
    "Errors that are none of the twelve (validation, stale version, not found, internal) have no `state`.",
    "",
  );
  return l.join("\n");
}

export function generatedFiles(): Record<string, string> {
  return {
    "openapi.json": `${JSON.stringify(buildSpec(), null, 2)}\n`,
    "SSE.md": sseMarkdown(),
    "STATES.md": statesMarkdown(),
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes("--check");
  const files = generatedFiles();
  let drift = 0;
  mkdirSync(DOCS_API_DIR, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const p = join(DOCS_API_DIR, name);
    const current = existsSync(p) ? readFileSync(p, "utf8") : null;
    if (check) {
      if (current !== content) {
        drift++;
        console.error(`DRIFT: docs/api/${name} differs from the generated output. Run \`pnpm api:openapi\`.`);
      }
    } else {
      writeFileSync(p, content);
      console.log(`wrote docs/api/${name}${current === content ? " (unchanged)" : ""}`);
    }
  }
  if (check) {
    if (drift) process.exit(1);
    console.log(
      `OpenAPI up to date: ${ROUTES.length} operations, ${Object.keys(buildSpec().components.schemas).length} schemas.`,
    );
  }
}
