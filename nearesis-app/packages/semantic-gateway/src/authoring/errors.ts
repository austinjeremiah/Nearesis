/** Typed authoring failure: `reason` is machine readable, `errorCode` is the public ErrorCode, `issues` carry paths. */
export class MetricAuthoringError extends Error {
  readonly errorCode: ErrorCode;
  constructor(
    readonly reason: MetricAuthoringReason,
    message: string,
    readonly issues: MetricIssue[] = [],
  ) {
    super(message);
    this.name = "MetricAuthoringError";
    this.errorCode = CODE[reason];
  }
}
