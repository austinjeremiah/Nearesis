const metrics: MetricMetadata[] = seeds.map(({ evaluator: _e, fixture, ...m }) => ({
  ...m,
  certifiedVersion: "1.0.0",
  certified: true,
  owner: "nearesis-analytics",
  docUri: `docs/metrics/METRICS.md#${m.id.replace(/\./g, "")}`,
  testFixture: fixture ?? "fx.snapshot.p02-baseline",
}));
const evaluators = Object.fromEntries(seeds.map((s) => [s.id, s.evaluator]));

const dimensions: RegistryDimension[] = CUBES.flatMap((c) => [
  {
    id: `${c.view}.day`,
    view: c.view,
    displayName: "Day (UTC)",
    kind: "time" as const,
    visibility: "public" as const,
  },
  ...c.dimensions.map((d) => ({
    id: `${c.view}.${d.name}`,
    view: c.view,
    displayName: d.name.replace(/_/g, " "),
    kind: "dimension" as const,
    visibility: RESTRICTED_DIMENSIONS.has(`${c.view}.${d.name}`)
      ? ("restricted" as const)
      : ("public" as const),
  })),
]);

const reg = sealRegistry({ semanticVersion: "1.0.0", metrics, dimensions, evaluators });
writeFileSync(join(REGISTRY_DIR, "metrics.v1.json"), stringifyRegistry(reg));
console.log(
  `wrote metrics.v1.json: ${metrics.length} metrics, ${dimensions.length} dimensions, hash ${reg.contentHash}`,
);
