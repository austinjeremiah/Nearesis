import type { Registry } from "../registry/types.ts";
import { CUBES, type CubeDef } from "./definition.ts";

const q = (s: string) => JSON.stringify(s);
/** Time-based refresh (Cube Core re-evaluates SQL refresh keys unreliably for ClickHouse rollups, see FND-20261110-501). */
export const REFRESH_EVERY = "5 second";

/** Renders one cube + its public view as Cube YAML. Metric metadata is copied from the registry into measure `meta` (S13: meta == registry). */
export function renderCubeFile(c: CubeDef, registry: Registry): string {
  const select = c.select ?? `SELECT * FROM ${c.table} FINAL`;
  const metricByMember = new Map(registry.metrics.map((m) => [m.cubeMember, m]));
  const L: string[] = [];
  L.push(
    "# GENERATED by scripts/gen-model.ts from src/model/definition.ts + registry/metrics.v*.json. Do not edit by hand.",
  );
  L.push("cubes:");
  L.push(`  - name: ${c.name}`);
  L.push(`    sql: ${q(select)}`);
  L.push("    public: false");
  L.push("    refresh_key:");
  L.push(`      every: ${REFRESH_EVERY}`);
  L.push("    dimensions:");
  L.push("      - name: day");
  L.push(`        sql: ${q(c.timeColumn)}`);
  L.push("        type: time");
  L.push('        description: "UTC day"');
  for (const d of c.dimensions) {
    L.push(
      `      - name: ${d.name}`,
      `        sql: ${q(d.sql)}`,
      `        type: ${d.type}`,
      `        description: ${q(d.description)}`,
    );
  }
  L.push("    measures:");
  for (const m of c.measures) {
    L.push(`      - name: ${m.name}`, `        type: ${m.type}`);
    if (m.sql) L.push(`        sql: ${q(m.sql)}`);
    if (m.filter) L.push("        filters:", `          - sql: ${q(m.filter)}`);
    L.push(`        description: ${q(m.description)}`);
    const meta = metricByMember.get(`${c.view}.${m.name}`);
    if (meta) L.push(`        meta: ${JSON.stringify(meta)}`);
  }
  if (c.rollups.length) {
    L.push("    pre_aggregations:");
    for (const r of c.rollups) {
      L.push(
        `      - name: ${r.name}`,
        `        measures: [${r.measures.join(", ")}]`,
        `        dimensions: [${r.dimensions.join(", ")}]`,
      );
      L.push("        time_dimension: day", "        granularity: day", "        external: false");
      L.push(
        "        indexes:",
        "          - name: idx_dims",
        `            columns: [${r.dimensions.join(", ")}]`,
      );
      L.push("        refresh_key:", `          every: ${REFRESH_EVERY}`);
    }
  }
  const exposed = [
    "day",
    ...c.dimensions.map((d) => d.name),
    ...c.measures.filter((m) => metricByMember.has(`${c.view}.${m.name}`)).map((m) => m.name),
  ];
  L.push("");
  L.push("views:");
  L.push(`  - name: ${c.view}`, "    public: true", "    cubes:");
  L.push(`      - join_path: ${c.name}`, "        includes:");
  for (const e of exposed) L.push(`          - ${e}`);
  return `${L.join("\n")}\n`;
}

export function renderAll(registry: Registry): Record<string, string> {
  return Object.fromEntries(CUBES.map((c) => [`${c.view}.yml`, renderCubeFile(c, registry)]));
}
